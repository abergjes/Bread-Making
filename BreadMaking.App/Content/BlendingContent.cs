        10.5 Stage-by-Stage: What Changes in a Blend

        Autolyse / fermentolyse: white-dominant blends take a normal 30–45 minute rest;
        high-wholegrain blends benefit from a longer 1–2 hour autolyse or a soaker; above roughly
        30% rye, einkorn or sprouted flour, shorten or skip the rest because the gluten is fragile
        and enzyme activity is high.

        Hydration: raise it for thirsty grains (wholegrain wheat, Kamut, rye, sorghum) and lower
        it for slack einkorn; add water gradually, as blends respond quickly.

        Mixing: the more low-gluten flour, the more you favour stretch-and-folds over kneading —
        aggressive kneading tears the weak network rather than building it.

        Bulk fermentation: bran and germ feed the yeast, so blends ferment faster than white dough;
        reduce the desired dough temperature and watch the dough, not the clock.

        Proofing: more ancient or wholegrain flour means a shorter proof and a higher over-proof
        risk; under-proof slightly rather than over-proof.

        Shaping: expect stickier, slacker dough as the low-gluten fraction rises; use wet hands,
        a bench knife and banneton or tin support.

        Baking: bake wholegrain and ancient blends a little cooler (around 190–220°C / 375–425°F)
        and tent with foil if the crust browns before the crumb sets; steam the first 15–20 minutes
        for spring and crust. Expect less oven spring and a tighter crumb than a white loaf.

        10.6 A Worked Example — 60% Emmer / 40% White Wheat Sourdough

        To make the principles concrete, here is how the 60/40 emmer blend from the brief would
        run through the full process. Quantities are in baker's percentages (flour totals 100%).

        Flour: 60% wholegrain emmer, 40% strong white bread flour.
        Water: start at 75% (emmer is moderately thirsty but its weak gluten will not hold the
        very highest hydrations).
        Starter: 20% ripe levain.
        Salt: 2%.

        Rest: a short 20-minute autolyse of the flours and water only — long enough to hydrate the
        emmer bran, short enough not to slacken the dough further.

        Mix & bulk: add levain and salt, then 3–4 sets of gentle coil folds in the first 2 hours.
        Bulk about 4–5 hours at 24–26°C — noticeably faster than an all-white dough.

        Shape & proof: shape with a light touch into a banneton for support; cold proof 10–14 hours
        at 4°C rather than a long warm proof, to limit over-proofing and firm the dough for scoring.

        Bake: 250°C / 480°F in a covered Dutch oven, 20 minutes covered, then 20–25 minutes
        uncovered at 225°C / 435°F. Expect a rustic, earthy loaf with a moderately open crumb
        and a faster-browning crust.
