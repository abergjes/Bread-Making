        10. Baking with Grain Blends

        Few bakers work with a single ancient grain at 100%. In practice the most reliable,
        best-tasting loaves come from blends — combining the flavour and nutrition of ancient or
        specialty grains with enough strong wheat (or a binder, for gluten-free mixes) to carry
        structure. This section explains how blending changes every stage of the process, from the
        rest through to the bake, and gives quantitative starting points for the four blend
        families you are most likely to use.

        10.1 The Gluten Budget — the One Idea Behind Every Blend

        Bread structure depends far more on glutenin (which gives elasticity and traps gas) than
        on total protein. This is the key to understanding blends, and it explains an apparent
        paradox: ancient wheats are often higher in total protein than modern bread wheat, yet they
        make weaker dough. The reason is the ratio of the two gluten proteins. Modern wheat has a
        low gliadin-to-glutenin ratio (roughly 1.5 to 3.8), so its dough is strong and elastic.
        Ancient wheats are gliadin-heavy — the ratio climbs through spelt and emmer up to around
        12 for einkorn — so their dough is extensible, sticky, slack and fragile.

        Think of every recipe as having a gluten budget. Strong modern wheat deposits into it;
        low-gluten ancient grains, and especially gluten-free flours, draw it down. The art of
        blending is keeping the budget high enough to hold structure while letting the flavour grain
        dominate. Once the low-gluten fraction climbs past roughly 40%, you compensate — by adding
        water for the thirstier grains, switching from kneading to gentle folds, supporting the
        dough in a banneton or tin, shortening the rest and the proof, and accepting a denser crumb.
        Above about 60% you usually add a structure aid (vital wheat gluten for wheat blends,
        psyllium or xanthan for gluten-free).

        Figure 7 — As the ancient or low-gluten fraction of a blend rises, target hydration climbs
        (thirstier bran and starch) while loaf volume and oven spring fall. The 40–60% band is the
        practical sweet spot where flavour dominates but structure still holds.

        10.2 Why 60/40 Is the Classic Ratio

        The most widely recommended starting point for an ancient-grain loaf is roughly 60% ancient
        grain to 40% strong white wheat. The 40% high-protein wheat supplies just enough glutenin
        backbone for a buoyant, sliceable crumb, while 60% ancient flour lets its flavour, colour
        and aroma lead. Bakers who have trialled the same recipe at 20%, 40% and 100% whole ancient
        grain consistently land on around 40% whole grain as the best balance of an open, fluffy
        crumb and whole-grain character — the 20% version is barely distinguishable from white,
        while a 100% loaf can be so slack it almost pours into the basket. If your only wheat flour
        is weak (around 10% protein), top up the budget with vital wheat gluten (see Section 11).

        10.3 Four Families of Blend

        (a) Ancient grain + white wheat — the structure-retaining classic
        This is the 60/40 approach and its neighbours. The white wheat carries the loaf, so the
        process stays close to a normal wheat bake: a standard 30–45 minute autolyse works,
        hydration sits around 70–78% for a sourdough, and you can shape free-form. Expect good
        oven spring, with slightly faster crust browning from carotenoid-rich grains like einkorn
        and Kamut. This family is the most forgiving and the best place to start.

        (b) Ancient grain + wholegrain wheat — maximum flavour and nutrition
        Replacing the white wheat with wholemeal pushes everything toward the whole-grain end: more
        flavour and fibre, a thirstier dough, faster fermentation and a denser crumb. A useful rule
        of thumb is to add roughly 3–4% water for every 25% wholegrain flour you introduce. A long
        autolyse (one to two hours) or a separate soaker of the wholegrain fraction helps the bran
        hydrate and stop it cutting the gluten. Drop the desired dough temperature to around
        23°C / 75°F, because wholegrain ferments vigorously and over-proofs readily.

        (c) Ancient + ancient — stacking the weaknesses
        Combining two ancient grains (emmer with spelt, einkorn with Kamut, spelt with Kamut)
        gives wonderful flavour but no strong-wheat backbone, so structure is the challenge. Let
        the thirstiest partner set the hydration — a spelt-and-Kamut dough can climb well above 80%
        because Kamut is so absorbent. Handle gently, support the loaf in a banneton or tin, and
        consider a small dose of vital wheat gluten (around 1%, with a matching increase in water)
        or a scald of part of the flour to firm things up. Of the ancient grains, Kamut behaves
        best and makes the most dependable structural partner.

        (d) Ancient or wheat + gluten-free — two different worlds
        There are two cases here. A small amount of a gluten-free grain (up to roughly 20–25% teff
        or sorghum) added to a wheat or ancient dough lends flavour, colour and nutrition while the
        wheat still carries structure — sorghum in particular is best capped around 25% before the
        crumb turns dry and tight. But a fully gluten-free blend (for example teff with sorghum and
        rice, or buckwheat with quinoa and millet) has no gluten budget at all. It is not kneaded
        dough but a batter, and structure must be rebuilt from a base flour, a starch and a binder.

